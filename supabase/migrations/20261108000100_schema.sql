begin;
create table if not exists public.categories (
 id smallint primary key, slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 name text not null, sort_order smallint not null default 0, icon text not null
);
create table if not exists public.rarities (
 id smallint primary key, slug text not null unique, name text not null,
 sort_order smallint not null default 0, color text not null
);
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text not null unique check (username ~ '^[a-z0-9_]{3,20}$'),
 roblox_username text check (roblox_username ~ '^[A-Za-z0-9_]{3,20}$'),
 roblox_user_id bigint check (roblox_user_id > 0), roblox_verified boolean not null default false,
 bio text not null default '' check (char_length(bio) <= 280),
 role text not null default 'user' check (role in ('user','moderator','admin','owner')),
 reputation integer not null default 0, trades_completed integer not null default 0 check (trades_completed >= 0),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.profile_private (
 id uuid primary key references public.profiles(id) on delete cascade,
 age_confirmed_at timestamptz, banned_until timestamptz, ban_reason text
);
create table if not exists public.items (
 id uuid primary key default gen_random_uuid(), slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 name text not null, category_id smallint not null references public.categories(id),
 rarity_id smallint references public.rarities(id), description text not null default '',
 obtain_method text not null default 'unknown' check (obtain_method in ('starter','pack','free_legendary_pack','daily_login','level_reward','promo_code','event','shop','beta','unknown')),
 obtain_note text, image_path text, value bigint check (value >= 0), demand smallint check (demand between 1 and 5),
 status text not null default 'active' check (status in ('active','retired','upcoming')),
 is_tradable boolean, released_at timestamptz, source_url text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.item_value_history (
 id bigint generated by default as identity primary key,
 item_id uuid not null references public.items(id) on delete cascade,
 value bigint check (value >= 0), demand smallint check (demand between 1 and 5), reason text,
 changed_by uuid references public.profiles(id) on delete set null, created_at timestamptz not null default now()
);
-- SYNC WITH SQL: MAX_COINS=1000000000000; LISTING_TTL_DAYS=7.
create table if not exists public.trade_listings (
 id uuid primary key default gen_random_uuid(), owner_id uuid not null references public.profiles(id) on delete cascade,
 status text not null default 'open' check (status in ('open','pending','completed','cancelled','expired')),
 coins_have bigint not null default 0 check (coins_have between 0 and 1000000000000),
 coins_want bigint not null default 0 check (coins_want between 0 and 1000000000000),
 note text not null default '' check (char_length(note) <= 280), accepts_offers boolean not null default true,
 expires_at timestamptz not null default now() + interval '7 days',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), completed_at timestamptz
);
create table if not exists public.trade_listing_items (
 listing_id uuid not null references public.trade_listings(id) on delete cascade,
 item_id uuid not null references public.items(id), side text not null check (side in ('have','want')),
 quantity smallint not null check (quantity between 1 and 99), primary key (listing_id,item_id,side)
);
create table if not exists public.trade_offers (
 id uuid primary key default gen_random_uuid(), listing_id uuid not null references public.trade_listings(id) on delete cascade,
 offerer_id uuid not null references public.profiles(id) on delete cascade,
 status text not null default 'pending' check (status in ('pending','accepted','declined','withdrawn','expired')),
 message text not null default '' check (char_length(message) <= 280),
 coins_offered bigint not null default 0 check (coins_offered between 0 and 1000000000000),
 created_at timestamptz not null default now(), responded_at timestamptz
);
create table if not exists public.trade_offer_items (
 offer_id uuid not null references public.trade_offers(id) on delete cascade,
 item_id uuid not null references public.items(id), quantity smallint not null check (quantity between 1 and 99),
 primary key (offer_id,item_id)
);
create table if not exists public.audit_log (
 id bigint generated by default as identity primary key,
 actor_id uuid references public.profiles(id) on delete set null,
 action text not null, entity text not null, entity_id uuid, diff jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create index if not exists items_category_idx on public.items(category_id);
create index if not exists items_rarity_idx on public.items(rarity_id);
create index if not exists history_item_created_idx on public.item_value_history(item_id,created_at desc);
create index if not exists history_actor_idx on public.item_value_history(changed_by);
create index if not exists listings_status_created_idx on public.trade_listings(status,created_at desc);
create index if not exists listings_owner_idx on public.trade_listings(owner_id);
create index if not exists listing_items_item_side_idx on public.trade_listing_items(item_id,side);
create index if not exists offers_listing_idx on public.trade_offers(listing_id);
create index if not exists offers_offerer_idx on public.trade_offers(offerer_id);
create unique index if not exists offers_one_pending_idx on public.trade_offers(listing_id,offerer_id) where status='pending';
create unique index if not exists offers_one_accepted_idx on public.trade_offers(listing_id) where status='accepted';
create index if not exists offer_items_item_idx on public.trade_offer_items(item_id);
create index if not exists audit_actor_idx on public.audit_log(actor_id);
create or replace function public.touch_updated_at() returns trigger language plpgsql set search_path='' as $$
begin new.updated_at=now(); return new; end $$;
drop trigger if exists profiles_touch on public.profiles;
create trigger profiles_touch before update on public.profiles for each row execute function public.touch_updated_at();
drop trigger if exists items_touch on public.items;
create trigger items_touch before update on public.items for each row execute function public.touch_updated_at();
drop trigger if exists listings_touch on public.trade_listings;
create trigger listings_touch before update on public.trade_listings for each row execute function public.touch_updated_at();
commit;
